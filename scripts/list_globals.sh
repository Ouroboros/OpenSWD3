#!/usr/bin/env bash
# Writes reverse/analysis/globals.tsv: every original global restored as a member (architecture v3), found in the
# headers under src/ by the address comment of its declaration ("// 0x00<address> ...") or by its name
# (unk<address>). Columns: address, owner::member, type, source (path:line), the comment of the declaration.
# Usage: scripts/list_globals.sh
set -eu
cd "$(dirname "$0")/.."
out="reverse/analysis/globals.tsv"
{
    printf '# Original globals and the members restoring them (generated by scripts/list_globals.sh).\n'
    printf '# address\tmember\ttype\tsource\tnotes\n'
    find src -name '*.h' | sort | while read -r file; do
        awk -v file="$file" '
            /^(class|struct) [A-Za-z_0-9]+/ && $0 !~ /;$/ { owner = $2 }
            /^    (class|struct) [A-Za-z_0-9]+/ && $0 !~ /;$/ { owner = $2 }
            /^    [A-Za-z_:<>, 0-9*&\[\]]+ [A-Za-z_0-9]+( = [^;]*|\{[^;]*\}|\[[^;]*\])?;/ {
                line = $0
                comment = ""
                at = index(line, "//")
                if (at > 0) { comment = substr(line, at + 3); line = substr(line, 1, at - 1) }
                address = ""
                if (match(comment, /^0x00[45][0-9A-F]{5}/)) { address = substr(comment, RSTART, RLENGTH); comment = substr(comment, RLENGTH + 2) }
                sub(/ = [^;]*;.*$/, ";", line); sub(/\{[^;]*\};.*$/, ";", line); sub(/;.*$/, "", line)
                sub(/^ +/, "", line)
                name = line; sub(/.* /, "", name); sub(/\[.*$/, "", name)
                type = line; sub(/ [A-Za-z_0-9\[\]]+$/, "", type)
                if (address == "" && match(name, /^unk[45][0-9A-F]{5}$/)) address = "0x00" substr(name, 4)
                if (address == "") next
                gsub(/\t/, " ", comment)
                print address "\t" owner "::" name "\t" type "\t" file ":" FNR "\t" comment
            }' "$file"
    done | sort -t$'\t' -k1,1 -k2,2
} > "$out"
echo "$(($(wc -l < "$out") - 2)) globals in $out"
