"""Writes src/text/big5_table.h: the code page 950 (Big5 as Windows has it) mapping between Unicode and the game's
two-byte codes, sorted for binary search both ways. Usage: python3 scripts/make_big5_table.py <out>"""

import sys


def main():
    decode = []
    encode = {}
    for lead in range(0x81, 0xFF):
        for trail in list(range(0x40, 0x7F)) + list(range(0xA1, 0xFF)):
            code = bytes([lead, trail])
            try:
                text = code.decode("cp950")
            except UnicodeDecodeError:
                continue
            if len(text) != 1 or ord(text) > 0xFFFF:
                continue
            unicode = ord(text)
            decode.append((lead << 8 | trail, unicode))
            try:
                encoded = text.encode("cp950")
            except UnicodeEncodeError:
                continue
            if len(encoded) == 2:
                encode[unicode] = encoded[0] << 8 | encoded[1]
    lines = [
        "#pragma once",
        "",
        "#include <array>",
        "",
        '#include "core/types.h"',
        "",
        "// Generated by scripts/make_big5_table.py from code page 950: do not edit.",
        "namespace swd3::big5_table",
        "{",
        "",
        "struct Pair",
        "{",
        "    u16 from;",
        "    u16 to;",
        "};",
        "",
        "// Unicode to Big5, sorted by Unicode.",
        "inline constexpr std::array<Pair, %d> kEncode = {{" % len(encode),
    ]
    for unicode in sorted(encode):
        lines.append("    {0x%04X, 0x%04X}," % (unicode, encode[unicode]))
    lines.append("}};")
    lines.append("")
    lines.append("// Big5 to Unicode, sorted by Big5.")
    lines.append("inline constexpr std::array<Pair, %d> kDecode = {{" % len(decode))
    for code, unicode in sorted(decode):
        lines.append("    {0x%04X, 0x%04X}," % (code, unicode))
    lines.append("}};")
    lines.append("")
    lines.append("}  // namespace swd3::big5_table")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
