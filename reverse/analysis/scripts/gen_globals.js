'use strict';
// Generates src/data/globals.h and src/data/relocs.inc.
// Inputs:
//   reverse/analysis/data_auto.tsv  (gen_data_auto.js: every IDA data head / code-referenced address)
//   reverse/analysis/data_map.tsv   (manual overrides: renamed globals, pointer tables, structs)
// data_map.tsv columns: addr  type  name  module  notes
//   type: C++ element type with optional array suffix, e.g. "DWORD", "HANDLE[6]", "char[260]", "Foo*[9]"
//   "@size <Type> <bytes>" declares a struct size; "@include <header>" adds an include to globals.h.
// Manual entries replace auto entries they overlap. Data pointer ("*") and code pointer ("code*") fields
// are relocated at startup (src/data/image.cpp).
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..', '..');
const autoPath = path.join(root, 'reverse', 'analysis', 'data_auto.tsv');
const mapPath = path.join(root, 'reverse', 'analysis', 'data_map.tsv');
const outHeader = path.join(root, 'src', 'data', 'globals.h');
const outRelocs = path.join(root, 'src', 'data', 'relocs.inc');

const IMAGE_BASE = 0x00499000;
const IMAGE_END = 0x0053f000;

const SIZES = {
  char: 1, 'signed char': 1, 'unsigned char': 1, BYTE: 1, bool: 1, CHAR: 1, 'std::int8_t': 1, 'std::uint8_t': 1,
  short: 2, 'unsigned short': 2, WORD: 2, 'std::int16_t': 2, 'std::uint16_t': 2,
  int: 4, unsigned: 4, 'unsigned int': 4, long: 4, DWORD: 4, UINT: 4, LONG: 4, BOOL: 4, 'std::int32_t': 4,
  'std::uint32_t': 4, float: 4, HANDLE: 4, HWND: 4, LPVOID: 4, 'code*': 4,
  double: 8, 'std::int64_t': 8, 'std::uint64_t': 8,
};
const structSizes = {};
const includes = new Set();

function parseType(type) {
  const m = /^(.*?)(\[(\d+|0x[0-9a-fA-F]+)\])?$/.exec(type.trim());
  const elem = m[1].trim();
  const count = m[3] ? Number(m[3]) : 0;
  let size;
  if (elem.endsWith('*')) size = 4;
  else if (SIZES[elem] !== undefined) size = SIZES[elem];
  else if (structSizes[elem] !== undefined) size = structSizes[elem];
  else throw new Error(`unknown size for type "${elem}"`);
  return { elem, count, elemSize: size, size: size * (count || 1) };
}

function readRows(file, manual) {
  const rows = [];
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const cols = line.split('\t');
    if (cols[0] === 'addr') continue;
    if (cols[0] === '@size') { structSizes[cols[1]] = Number(cols[2]); continue; }
    if (cols[0] === '@include') { includes.add(cols[1]); continue; }
    rows.push({ addr: Number(cols[0]), type: cols[1].trim(), name: cols[2].trim(), notes: (cols[4] || '').trim(), manual });
  }
  return rows;
}

const manual = readRows(mapPath, true).map((r) => ({ ...r, ...parseType(r.type) }));
const auto = readRows(autoPath, false).map((r) => ({ ...r, ...parseType(r.type) }));
manual.sort((a, b) => a.addr - b.addr);
for (let i = 1; i < manual.length; i++) {
  if (manual[i].addr < manual[i - 1].addr + manual[i - 1].size) {
    throw new Error(`manual overlap: ${manual[i - 1].name} / ${manual[i].name}`);
  }
}
const manualNames = new Set(manual.map((m) => m.name));
const kept = auto.filter((a) => !manual.some((m) => a.addr >= m.addr && a.addr < m.addr + m.size) && !manualNames.has(a.name));
let rows = [...manual, ...kept].sort((a, b) => a.addr - b.addr);

// Shrink auto arrays that run into the next field.
for (let i = 0; i < rows.length - 1; i++) {
  const r = rows[i];
  const next = rows[i + 1].addr;
  if (r.addr + r.size <= next) continue;
  if (r.manual) throw new Error(`auto field ${rows[i + 1].name} inside manual field ${r.name}`);
  const room = next - r.addr;
  if (room >= r.elemSize && room % r.elemSize === 0) {
    const count = room / r.elemSize;
    Object.assign(r, parseType(count > 1 ? `${r.elem}[${count}]` : r.elem));
  } else {
    Object.assign(r, parseType(`std::uint8_t[${room}]`));
  }
}

let out = '#pragma once\n// Generated by reverse/analysis/scripts/gen_globals.js. Do not edit.\n\n';
out += '#include <cstddef>\n#include <cstdint>\n\n#include "data/image.h"\n#include "swd3/w32.h"\n';
for (const inc of [...includes].sort()) out += `#include "${inc}"\n`;
out += '\nnamespace swd3 {\n\nusing code_ptr = std::uint32_t;\n\n#pragma pack(push, 1)\nstruct Globals {\n';
let cursor = IMAGE_BASE;
for (const r of rows) {
  if (r.addr >= IMAGE_END || r.addr + r.size > IMAGE_END) throw new Error(`out of image: ${r.name}`);
  if (r.addr > cursor) out += `    std::uint8_t pad_${cursor.toString(16).toUpperCase()}[0x${(r.addr - cursor).toString(16).toUpperCase()}];\n`;
  const elem = r.elem === 'code*' ? 'code_ptr' : r.elem;
  const hex = `0x${r.addr.toString(16).toUpperCase().padStart(8, '0')}`;
  out += `    ${elem} ${r.name}${r.count ? `[${r.count}]` : ''};  // ${hex}${r.notes ? ' ' + r.notes : ''}\n`;
  cursor = r.addr + r.size;
}
if (cursor < IMAGE_END) out += `    std::uint8_t pad_${cursor.toString(16).toUpperCase()}[0x${(IMAGE_END - cursor).toString(16).toUpperCase()}];\n`;
out += '};\n#pragma pack(pop)\n\nstatic_assert(sizeof(Globals) == image::kSize);\n';
for (const r of rows.filter((x) => x.manual)) {
  out += `static_assert(offsetof(Globals, ${r.name}) == 0x${(r.addr - IMAGE_BASE).toString(16).toUpperCase()});\n`;
}
out += '\ninline Globals& globals() { return *reinterpret_cast<Globals*>(image::g_bytes); }\n\n}  // namespace swd3\n\n';
out += '#define G (::swd3::globals())\n';
fs.writeFileSync(outHeader, out);

let rel = '// Generated by reverse/analysis/scripts/gen_globals.js. {va, element count, kind}\n';
for (const r of rows) {
  const kind = r.elem === 'code*' ? 'image::RelocKind::Code' : r.elem.endsWith('*') ? 'image::RelocKind::Data' : null;
  if (kind) rel += `{0x${r.addr.toString(16).toUpperCase()}u, ${r.count || 1}u, ${kind}},  // ${r.name}\n`;
}
fs.writeFileSync(outRelocs, rel);
console.log(`globals: ${rows.length} fields (${manual.length} manual)`);
